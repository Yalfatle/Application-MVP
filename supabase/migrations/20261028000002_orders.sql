alter publication supabase_realtime add table public.orders, public.runner_locations;

-- Signed-in users only (functions are executable by everyone by default).
revoke execute on function public.update_order_status(uuid, public.order_status, text) from public, anon;
revoke execute on function public.assign_runner(uuid, uuid) from public, anon;
revoke execute on function public.update_runner_location(uuid, double precision, double precision, real, real) from public, anon;
revoke execute on function public.lab_earnings(timestamptz, timestamptz) from public, anon;
grant execute on function public.update_order_status(uuid, public.order_status, text) to authenticated;
grant execute on function public.assign_runner(uuid, uuid) to authenticated;
grant execute on function public.update_runner_location(uuid, double precision, double precision, real, real) to authenticated;
grant execute on function public.lab_earnings(timestamptz, timestamptz) to authenticated;
