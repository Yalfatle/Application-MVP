-- =====================================================================
-- Orders, status history, runner live location
-- =====================================================================
-- Order lifecycle:
--   pending ──► accepted ──► on_way ──► sample_taken ──► completed
--      │           │
--      ├► refused  └► cancelled
--      └► cancelled
-- Every change goes through update_order_status(), which checks who is
-- allowed to make it. Nobody (except super admins) can UPDATE orders
-- directly, so prices, commission and status can't be tampered with.
-- =====================================================================

create type public.order_status as enum
  ('pending', 'accepted', 'refused', 'on_way', 'sample_taken', 'completed', 'cancelled');

create table public.orders (
  id                 uuid primary key default gen_random_uuid(),
  -- Generated by the phone before sending. If a weak connection makes the
  -- app retry, the same order can't be created twice.
  client_request_id  uuid not null unique,
  patient_id         uuid not null references public.profiles on delete restrict,
  lab_id             uuid not null references public.labs on delete restrict,
  package_id         uuid references public.packages on delete set null,
  -- Snapshot at booking time, so later price/name edits don't rewrite history.
  package_name_ar    text not null,
  package_name_en    text not null,
  price_iqd          integer not null check (price_iqd >= 0),
  commission_rate    numeric(5,4) not null,
  commission_iqd     integer not null,
  payment_method     text not null default 'cash' check (payment_method in ('cash')),
  status             public.order_status not null default 'pending',
  -- Where the runner goes: the pin the patient dropped on the map.
  location_lat       double precision not null check (location_lat between -90 and 90),
  location_lng       double precision not null check (location_lng between -180 and 180),
  location_note      text check (length(location_note) <= 300), -- "3rd floor, green door"
  preferred_time     timestamptz,
  runner_id          uuid references public.profiles on delete set null,
  status_reason      text check (length(status_reason) <= 500),   -- refusal / cancellation reason
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  accepted_at        timestamptz,
  dispatched_at      timestamptz,
  sample_taken_at    timestamptz,
  completed_at       timestamptz,
  closed_at          timestamptz   -- refused / cancelled
);
create index orders_patient_idx on public.orders (patient_id, created_at desc);
create index orders_lab_idx     on public.orders (lab_id, status, created_at desc);
create index orders_runner_idx  on public.orders (runner_id) where runner_id is not null;

create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

create table public.order_events (
  id           bigint generated always as identity primary key,
  order_id     uuid not null references public.orders on delete cascade,
  from_status  public.order_status,
  to_status    public.order_status not null,
  actor_id     uuid references public.profiles on delete set null,
  note         text,
  created_at   timestamptz not null default now()
);
create index order_events_order_idx on public.order_events (order_id, created_at);

-- Live runner position. One row per order, only while the runner is on the way.
create table public.runner_locations (
  order_id    uuid primary key references public.orders on delete cascade,
  runner_id   uuid not null references public.profiles on delete cascade,
  lat         double precision not null,
  lng         double precision not null,
  heading     real,
  accuracy_m  real,
  updated_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------------
-- Booking: the server fills in price, names and commission itself.
-- ---------------------------------------------------------------------
create or replace function public.prepare_new_order()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  pkg  public.packages;
  lab  public.labs;
begin
  if not public.is_backend() then
    new.patient_id := auth.uid();
  end if;
  if new.patient_id is null then
    raise exception 'must be signed in to book';
  end if;

  select * into pkg from public.packages where id = new.package_id;
  if pkg.id is null or not pkg.is_active then
    raise exception 'package not available';
  end if;
  select * into lab from public.labs where id = pkg.lab_id;
  if not lab.is_active then
    raise exception 'lab not available';
  end if;

  new.lab_id          := pkg.lab_id;
  new.package_name_ar := pkg.name_ar;
  new.package_name_en := pkg.name_en;
  new.price_iqd       := pkg.price_iqd;
  new.commission_rate := coalesce(lab.commission_rate, (select commission_rate from public.app_settings));
  new.commission_iqd  := round(pkg.price_iqd * new.commission_rate);
  new.status          := 'pending';
  new.runner_id       := null;
  new.created_at      := now();
  return new;
end $$;

create trigger orders_prepare before insert on public.orders
  for each row execute function public.prepare_new_order();

create or replace function public.log_order_created()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.order_events (order_id, from_status, to_status, actor_id)
  values (new.id, null, new.status, new.patient_id);
  return new;
end $$;

create trigger orders_log_created after insert on public.orders
  for each row execute function public.log_order_created();

-- ---------------------------------------------------------------------
-- Has this patient ever booked with this lab? Staff visibility hangs on it.
-- ---------------------------------------------------------------------
create or replace function public.patient_booked_with_lab(p_patient uuid, p_lab uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.orders where patient_id = p_patient and lab_id = p_lab)
$$;

-- Is the current user staff (clerk or above) at a lab this patient booked with?
create or replace function public.can_staff_see_patient(p_patient uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_super_admin() or exists (
    select 1 from public.profiles me
    join public.orders o on o.lab_id = me.lab_id and o.patient_id = p_patient
    where me.id = auth.uid() and me.role in ('clerk', 'runner', 'lab_admin')
  )
$$;

-- ---------------------------------------------------------------------
-- Status changes
-- ---------------------------------------------------------------------
create or replace function public.update_order_status(
  p_order_id uuid,
  p_status   public.order_status,
  p_reason   text default null
) returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  o       public.orders;
  me      uuid := auth.uid();
  is_pat  boolean;
  ok      boolean := false;
  prev    public.order_status;
begin
  select * into o from public.orders where id = p_order_id for update;
  if o.id is null then raise exception 'order not found'; end if;

  is_pat := (o.patient_id = me);
  prev   := o.status;

  ok := case
    -- patient can cancel before the runner leaves
    when p_status = 'cancelled' and o.status in ('pending', 'accepted') and is_pat then true
    -- lab staff decide on new orders, and may cancel accepted ones
    when p_status in ('accepted', 'refused') and o.status = 'pending'
         then public.has_lab_role(o.lab_id, 'clerk')
    when p_status = 'cancelled' and o.status in ('pending', 'accepted')
         then public.has_lab_role(o.lab_id, 'clerk')
    -- the assigned runner (or a lab admin) dispatches and collects
    when p_status = 'on_way' and o.status = 'accepted'
         then (o.runner_id = me and public.has_lab_role(o.lab_id, 'runner'))
              or public.has_lab_role(o.lab_id, 'lab_admin')
    when p_status = 'sample_taken' and o.status = 'on_way'
         then (o.runner_id = me and public.has_lab_role(o.lab_id, 'runner'))
              or public.has_lab_role(o.lab_id, 'lab_admin')
    -- results delivered
    when p_status = 'completed' and o.status = 'sample_taken'
         then public.has_lab_role(o.lab_id, 'clerk')
    else false
  end;

  if not ok then
    raise exception 'status change % -> % not allowed', o.status, p_status;
  end if;
  if p_status = 'on_way' and o.runner_id is null then
    raise exception 'assign a runner first';
  end if;

  update public.orders set
    status          = p_status,
    status_reason   = case when p_status in ('refused', 'cancelled') then left(p_reason, 500) else status_reason end,
    accepted_at     = case when p_status = 'accepted'     then now() else accepted_at end,
    dispatched_at   = case when p_status = 'on_way'       then now() else dispatched_at end,
    sample_taken_at = case when p_status = 'sample_taken' then now() else sample_taken_at end,
    completed_at    = case when p_status = 'completed'    then now() else completed_at end,
    closed_at       = case when p_status in ('refused', 'cancelled') then now() else closed_at end
  where id = o.id
  returning * into o;

  insert into public.order_events (order_id, from_status, to_status, actor_id, note)
  values (o.id, prev, p_status, me, p_reason);

  -- Tracking stops the moment the runner is no longer on the way.
  if p_status <> 'on_way' then
    delete from public.runner_locations where order_id = o.id;
  end if;

  return o;
end $$;

-- Assign a runner. Clerks and admins can assign anyone in their lab;
-- a runner can pick up an unassigned accepted order themselves.
create or replace function public.assign_runner(p_order_id uuid, p_runner_id uuid)
returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  o public.orders;
begin
  select * into o from public.orders where id = p_order_id for update;
  if o.id is null then raise exception 'order not found'; end if;
  if o.status <> 'accepted' then raise exception 'order must be accepted first'; end if;

  if not exists (select 1 from public.profiles
                 where id = p_runner_id and lab_id = o.lab_id and role in ('runner', 'lab_admin')) then
    raise exception 'that person is not a runner at this lab';
  end if;

  if not (public.has_lab_role(o.lab_id, 'clerk') and public.my_role() <> 'runner')
     and not (p_runner_id = auth.uid() and o.runner_id is null and public.has_lab_role(o.lab_id, 'runner')) then
    raise exception 'not allowed to assign this order';
  end if;

  update public.orders set runner_id = p_runner_id where id = o.id returning * into o;
  return o;
end $$;

-- The runner's phone calls this every ~15 s while on the way.
create or replace function public.update_runner_location(
  p_order_id uuid, p_lat double precision, p_lng double precision,
  p_heading real default null, p_accuracy real default null
) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.orders
                 where id = p_order_id and runner_id = auth.uid() and status = 'on_way') then
    raise exception 'not the runner for an active trip';
  end if;
  insert into public.runner_locations (order_id, runner_id, lat, lng, heading, accuracy_m, updated_at)
  values (p_order_id, auth.uid(), p_lat, p_lng, p_heading, p_accuracy, now())
  on conflict (order_id) do update
    set lat = excluded.lat, lng = excluded.lng, heading = excluded.heading,
        accuracy_m = excluded.accuracy_m, updated_at = now();
end $$;

-- ---------------------------------------------------------------------
-- Earnings summary (super admins: all labs; lab admins: their own)
-- ---------------------------------------------------------------------
create or replace function public.lab_earnings(p_from timestamptz, p_to timestamptz)
returns table (lab_id uuid, lab_name_en text, lab_name_ar text,
               completed_orders bigint, revenue_iqd bigint, commission_iqd bigint)
language sql stable security definer set search_path = '' as $$
  select l.id, l.name_en, l.name_ar,
         count(o.id), coalesce(sum(o.price_iqd), 0), coalesce(sum(o.commission_iqd), 0)
  from public.labs l
  left join public.orders o
    on o.lab_id = l.id and o.status = 'completed'
   and o.completed_at >= p_from and o.completed_at < p_to
  where public.is_super_admin() or public.has_lab_role(l.id, 'lab_admin')
  group by l.id
  order by 6 desc
$$;

-- ---------------------------------------------------------------------
-- Row level security
-- ---------------------------------------------------------------------
alter table public.orders           enable row level security;
alter table public.order_events     enable row level security;
alter table public.runner_locations enable row level security;

create policy orders_read on public.orders for select to authenticated
  using (patient_id = (select auth.uid()) or public.has_lab_role(lab_id, 'clerk'));
create policy orders_insert on public.orders for insert to authenticated
  with check (patient_id = (select auth.uid()));
create policy orders_admin_update on public.orders for update to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());
create policy orders_admin_delete on public.orders for delete to authenticated
  using (public.is_super_admin());

create policy order_events_read on public.order_events for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id
                 and (o.patient_id = (select auth.uid()) or public.has_lab_role(o.lab_id, 'clerk'))));

create policy runner_locations_read on public.runner_locations for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id
                 and (o.patient_id = (select auth.uid()) or public.has_lab_role(o.lab_id, 'clerk'))));

-- Profile visibility that depends on orders:
-- staff see the names of patients who booked with their lab,
-- patients see the name of the runner coming to them.
create policy profiles_read_my_patients on public.profiles for select to authenticated
  using (role = 'patient' and public.can_staff_see_patient(id));
create policy profiles_read_my_runner on public.profiles for select to authenticated
  using (exists (select 1 from public.orders o
                 where o.runner_id = profiles.id and o.patient_id = (select auth.uid())));

